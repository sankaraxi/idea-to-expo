  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_evaluators_user` (`user_id`),
  UNIQUE KEY `uq_evaluators_email` (`email`),
  UNIQUE KEY `uq_evaluators_employee` (`employee_id`),
  KEY `ix_evaluators_status` (`status`),
  CONSTRAINT `chk_evaluators_email_lower` CHECK (BINARY `email` = BINARY LOWER(`email`)),
  CONSTRAINT `fk_evaluators_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Evaluation criteria and domains (admin-defined)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS `evaluation_criteria` (
  `id`            CHAR(36)     NOT NULL DEFAULT (UUID()),
  `name`          VARCHAR(120) NOT NULL,
  `description`   VARCHAR(1000) NULL,
  `max_marks`     SMALLINT UNSIGNED NOT NULL,
  `input_style`   ENUM('STARS','SLIDER','NUMBER') NOT NULL DEFAULT 'SLIDER',
  `sort_order`    INT          NOT NULL DEFAULT 0,
  `is_active`     TINYINT(1)   NOT NULL DEFAULT 1,
  -- Header of the score column in the problem statement sheet (defaults to name).
  `sheet_column`  VARCHAR(200) NULL,
  `created_at`    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at`    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_criteria_name` (`name`),
  CONSTRAINT `chk_criteria_max` CHECK (`max_marks` BETWEEN 1 AND 100),
  CONSTRAINT `chk_criteria_stars` CHECK (`input_style` <> 'STARS' OR `max_marks` <= 10)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `domains` (
  `id`          CHAR(36)    NOT NULL DEFAULT (UUID()),
  `name`        VARCHAR(80) NOT NULL,
  `sort_order`  INT         NOT NULL DEFAULT 0,
  `is_active`   TINYINT(1)  NOT NULL DEFAULT 1,
  `created_at`  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at`  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_domains_name` (`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Evaluations: ONE evaluator per student (unique student_id).
-- The first save claims the student; the row lock + this key make that safe
-- when two evaluators try at the same moment.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS `evaluations` (
  `id`            CHAR(36)    NOT NULL DEFAULT (UUID()),
  `student_id`    CHAR(36)    NOT NULL,
  `evaluator_id`  CHAR(36)    NOT NULL,
  `remarks`       TEXT        NULL,
  `status`        ENUM('IN_PROGRESS','COMPLETED') NOT NULL DEFAULT 'IN_PROGRESS',
  `version`       INT         NOT NULL DEFAULT 1,
  `total_score`   INT         NULL,
  `max_total`     INT         NULL,
  `started_at`    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `submitted_at`  DATETIME(3) NULL,
  `created_at`    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at`    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_evaluations_student` (`student_id`),
  KEY `ix_evaluations_evaluator` (`evaluator_id`, `status`),
  KEY `ix_evaluations_status` (`status`),
  CONSTRAINT `chk_evaluations_remarks` CHECK (`remarks` IS NULL OR CHAR_LENGTH(`remarks`) <= 5000),
  CONSTRAINT `chk_evaluations_completed` CHECK (
    `status` <> 'COMPLETED'
    OR (`total_score` IS NOT NULL AND `max_total` IS NOT NULL AND `submitted_at` IS NOT NULL)),
  CONSTRAINT `fk_evaluations_student` FOREIGN KEY (`student_id`) REFERENCES `students` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_evaluations_evaluator` FOREIGN KEY (`evaluator_id`) REFERENCES `evaluators` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `evaluation_scores` (
  `evaluation_id`  CHAR(36) NOT NULL,
  `criterion_id`   CHAR(36) NOT NULL,
  `score`          INT      NOT NULL,
  PRIMARY KEY (`evaluation_id`, `criterion_id`),
  KEY `ix_scores_criterion` (`criterion_id`),
  CONSTRAINT `chk_scores_nonneg` CHECK (`score` >= 0),
  CONSTRAINT `fk_scores_evaluation` FOREIGN KEY (`evaluation_id`) REFERENCES `evaluations` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_scores_criterion` FOREIGN KEY (`criterion_id`) REFERENCES `evaluation_criteria` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `evaluation_domains` (
  `evaluation_id`  CHAR(36) NOT NULL,
  `domain_id`      CHAR(36) NOT NULL,
  PRIMARY KEY (`evaluation_id`, `domain_id`),
  KEY `ix_eval_domains_domain` (`domain_id`),
  CONSTRAINT `fk_eval_domains_evaluation` FOREIGN KEY (`evaluation_id`) REFERENCES `evaluations` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_eval_domains_domain` FOREIGN KEY (`domain_id`) REFERENCES `domains` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

