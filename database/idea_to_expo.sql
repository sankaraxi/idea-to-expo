-- Coalescing: `pending_key` is non-NULL only while a job is PENDING, so the
-- unique key allows at most ONE pending job per entity. A job that is already
-- PROCESSING does not block a new PENDING one, so a change made while the
-- worker is mid-flight is never lost.
CREATE TABLE IF NOT EXISTS `sheet_sync_queue` (
  `id`             CHAR(36)    NOT NULL DEFAULT (UUID()),
  `entity_type`    ENUM('STUDENT','EVALUATOR','EVALUATION','RESULTS','RESPONSE_ROW') NOT NULL,
  `entity_id`      CHAR(36)    NOT NULL,
  `status`         ENUM('PENDING','PROCESSING','SUCCESS','FAILED','SUPERSEDED') NOT NULL DEFAULT 'PENDING',
  `attempts`       INT         NOT NULL DEFAULT 0,
  `last_error`     TEXT        NULL,
  `next_retry_at`  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `locked_at`      DATETIME(3) NULL,
  `created_at`     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `processed_at`   DATETIME(3) NULL,
  `pending_key`    VARCHAR(80) GENERATED ALWAYS AS (
                     IF(`status` = 'PENDING', CONCAT(`entity_type`, ':', `entity_id`), NULL)) VIRTUAL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_sync_pending` (`pending_key`),
  KEY `ix_sync_claim` (`status`, `next_retry_at`),
  KEY `ix_sync_created` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `sync_locks` (
  `name`         VARCHAR(60) NOT NULL,
  `holder`       VARCHAR(64) NULL,
  `lease_until`  DATETIME(3) NOT NULL DEFAULT '1970-01-01 00:00:00.000',
  PRIMARY KEY (`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `form_sync_runs` (
  `id`            CHAR(36)    NOT NULL DEFAULT (UUID()),
  `source`        ENUM('APPS_SCRIPT','SHEETS_PULL','CSV_IMPORT') NOT NULL,
  `status`        ENUM('SUCCESS','PARTIAL','FAILED') NOT NULL,
  `received`      INT         NOT NULL DEFAULT 0,
  `inserted`      INT         NOT NULL DEFAULT 0,
  `updated`       INT         NOT NULL DEFAULT 0,
  `unchanged`     INT         NOT NULL DEFAULT 0,
  `skipped`       INT         NOT NULL DEFAULT 0,
  `errors`        JSON        NOT NULL DEFAULT (JSON_ARRAY()),
  `triggered_by`  CHAR(36)    NULL,
  `created_at`    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  KEY `ix_form_runs_created` (`created_at`),
  CONSTRAINT `fk_form_runs_user` FOREIGN KEY (`triggered_by`) REFERENCES `users` (`id`) ON DELETE SET NULL
