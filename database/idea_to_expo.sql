-- =============================================================================
-- Idea to Expo — MySQL schema + defaults
--
-- Target: MySQL 8.0.16+ (developed and tested on MySQL 9.1). Uses CHECK
-- constraints, JSON columns, expression defaults and generated columns.
--
-- Import (creates the database `idea_to_expo` if it does not exist):
--     mysql -u root -p < database/idea_to_expo.sql
-- or in MySQL Workbench: File → Run SQL Script…
--
-- Re-running is safe: every table is created with IF NOT EXISTS and the
-- default rows are only inserted when missing. It never drops anything.
--
-- All timestamps are UTC (the app sets `time_zone = '+00:00'` per connection).
-- Rows are keyed by UUID strings generated by the application; the DEFAULT
-- (UUID()) is only a convenience for manual inserts.
-- =============================================================================

CREATE DATABASE IF NOT EXISTS `idea_to_expo`
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `idea_to_expo`;

SET NAMES utf8mb4;

-- ---------------------------------------------------------------------------
-- Accounts & sessions (replaces Supabase Auth)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS `users` (
  `id`             CHAR(36)     NOT NULL DEFAULT (UUID()),
  `email`          VARCHAR(255) NOT NULL,
  `password_hash`  VARCHAR(255) NOT NULL,
  `role`           ENUM('ADMIN','EVALUATOR') NOT NULL,
  `full_name`      VARCHAR(200) NULL,
  `is_active`      TINYINT(1)   NOT NULL DEFAULT 1,
  `last_login_at`  DATETIME(3)  NULL,
  `created_at`     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at`     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_users_email` (`email`),
  CONSTRAINT `chk_users_email_lower` CHECK (BINARY `email` = BINARY LOWER(`email`))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- The cookie holds a random token; only its SHA-256 hash is stored here.
CREATE TABLE IF NOT EXISTS `sessions` (
  `id`            CHAR(64)     NOT NULL,
  `user_id`       CHAR(36)     NOT NULL,
  `expires_at`    DATETIME(3)  NOT NULL,
  `created_at`    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `last_seen_at`  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `ip`            VARCHAR(64)  NULL,
  `user_agent`    VARCHAR(255) NULL,
  PRIMARY KEY (`id`),
  KEY `ix_sessions_user` (`user_id`),
  KEY `ix_sessions_expires` (`expires_at`),
  CONSTRAINT `fk_sessions_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Settings (single row, id = 1)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS `app_settings` (
  `id`                  TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `event_status`        ENUM('NOT_STARTED','LIVE','PAUSED','CLOSED') NOT NULL DEFAULT 'NOT_STARTED',
  -- When on, evaluators may revise a submitted evaluation while the event is LIVE.
  `allow_resubmission`  TINYINT(1)   NOT NULL DEFAULT 0,
  -- Ordered tie-break rule ids, interpreted by lib/results/ranking.ts.
  `tie_breakers`        JSON         NOT NULL DEFAULT (JSON_ARRAY()),
  -- Problem statement form header -> portal field mapping (lib/forms/mapping.ts).
  `form_field_mapping`  JSON         NOT NULL DEFAULT (JSON_OBJECT()),
  -- {"total_header": "...", "evaluator_header": "...", "domains_header": "..."}
  `sheet_writeback`     JSON         NOT NULL DEFAULT (JSON_OBJECT()),
  `updated_at`          DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  `updated_by`          CHAR(36)     NULL,
  PRIMARY KEY (`id`),
  CONSTRAINT `chk_app_settings_singleton` CHECK (`id` = 1),
  CONSTRAINT `fk_app_settings_user` FOREIGN KEY (`updated_by`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT INTO `app_settings` (`id`) VALUES (1) ON DUPLICATE KEY UPDATE `id` = `id`;

-- ---------------------------------------------------------------------------
-- Students (CSV master data) and their problem statement submission
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS `students` (
  `id`                  CHAR(36)     NOT NULL DEFAULT (UUID()),
  -- Upper-case, no whitespace; the unique student identifier.
  `register_number`     VARCHAR(64)  NOT NULL,
  `name`                VARCHAR(255) NOT NULL,
  `gender`              VARCHAR(30)  NULL,
  `department`          VARCHAR(120) NULL,
  `year`                TINYINT UNSIGNED NULL,
  `section`             VARCHAR(30)  NULL,
  `email`               VARCHAR(255) NULL,
  `phone`               VARCHAR(40)  NULL,
  `status`              ENUM('ACTIVE','WITHDRAWN','DISQUALIFIED') NOT NULL DEFAULT 'ACTIVE',
  `source`              ENUM('FORM','IMPORT','MANUAL','SEED') NOT NULL DEFAULT 'IMPORT',
  `form_submitted_at`   DATETIME(3)  NULL,
  -- Optional admin-defined tie-break (lower wins), used by ADMIN_PRIORITY_ASC.
  `tie_break_priority`  INT          NULL,
  `created_at`          DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at`          DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_students_register_number` (`register_number`),
  UNIQUE KEY `uq_students_email` (`email`),
  KEY `ix_students_department` (`department`),
  KEY `ix_students_status` (`status`),
  KEY `ix_students_name` (`name`),
  CONSTRAINT `chk_students_register_number` CHECK (
    `register_number` <> '' AND `register_number` NOT REGEXP '[[:space:]]'
    AND BINARY `register_number` = BINARY UPPER(`register_number`)),
  CONSTRAINT `chk_students_email_lower` CHECK (`email` IS NULL OR BINARY `email` = BINARY LOWER(`email`)),
  CONSTRAINT `chk_students_year` CHECK (`year` IS NULL OR `year` BETWEEN 1 AND 6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- One submission per student today. The FK lives here (not on students), so
-- moving to multiple projects/teams later only means dropping the unique key.
CREATE TABLE IF NOT EXISTS `ideas` (
  `id`                 CHAR(36)      NOT NULL DEFAULT (UUID()),
  `student_id`         CHAR(36)      NOT NULL,
  `problem_statement`  MEDIUMTEXT    NULL,
  `abstract`           MEDIUMTEXT    NULL,
  `ppt_url`            VARCHAR(2048) NULL,
  `other_details`      JSON          NOT NULL DEFAULT (JSON_OBJECT()),
  `submission_status`  ENUM('SUBMITTED','INCOMPLETE') NOT NULL DEFAULT 'SUBMITTED',
  `submitted_at`       DATETIME(3)   NULL,
  -- Row number of the latest response in the problem statement sheet.
  `response_row`       INT           NULL,
  -- How the form response was linked to the student record.
  `matched_by`         ENUM('REGISTER_NUMBER','EMAIL','CREATED') NOT NULL DEFAULT 'REGISTER_NUMBER',
  `created_at`         DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at`         DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_ideas_student` (`student_id`),
  CONSTRAINT `fk_ideas_student` FOREIGN KEY (`student_id`) REFERENCES `students` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Evaluators. There is NO limit on how many students an evaluator can take.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS `evaluators` (
  `id`           CHAR(36)     NOT NULL DEFAULT (UUID()),
  `user_id`      CHAR(36)     NULL,
